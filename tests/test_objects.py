def body(project: Project, rel: str) -> str:
    text = project.read(rel)
    return text.split("\n\n", 1)[1]  # drop the two-line header


def test_expected_files(full: Project):
    assert full.files() == EXPECTED_FILES


def test_tables(full: Project):
    articles = body(full, "tables/app.articles.sql")
    assert "    id serial,\n" in articles
    assert "status app.status DEFAULT 'draft'::app.status NOT NULL" in articles
    assert "price_with_tax numeric GENERATED ALWAYS AS (price * 1.2) STORED" in articles
    assert "ALTER TABLE app.articles REPLICA IDENTITY FULL;" in articles
    assert "COMMENT ON COLUMN app.articles.title IS 'Headline; must not be blank';" in articles
    assert "CONSTRAINT" not in articles and "PRIMARY KEY" not in articles  # owned by constraints/

    authors = body(full, "tables/app.authors.sql")
    assert "id bigint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 10 START WITH 1000)" in authors
    assert 'display_name text COLLATE pg_catalog."C" NOT NULL' in authors  # renamed column
    assert "SET STATISTICS 500" in authors

    assert body(full, "tables/app.counters.sql").startswith("CREATE SEQUENCE app.custom_seq\n    START WITH 100;")
    assert "PARTITION OF app.events\n    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');" in \
        body(full, "tables/app.events_2026.sql")
    assert "INHERITS (app.base_log)" in body(full, "tables/app.audit_log.sql")
    assert body(full, "tables/app.scratch.sql").startswith("CREATE UNLOGGED TABLE app.scratch")
    assert '"Dark.Mode" boolean DEFAULT false' in body(full, "tables/App Data.User Settings.sql")


