    assert "DEFERRABLE INITIALLY DEFERRED" in body(full, "constraints/app.articles.articles_author_fk.sql")
    assert "NOT VALID" in body(full, "constraints/app.articles.title_not_blank.sql")
    assert "EXCLUDE USING gist" in body(full, "constraints/app.articles.no_overlap.sql")
    # index changed from plain to unique with INCLUDE
