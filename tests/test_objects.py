def _round_trip_sql(p: Project) -> str:
    files = p.snapshot()

    def pick(prefix: str, exclude: tuple[str, ...] = ()) -> list[str]:
        return [f for f in sorted(files) if f.startswith(prefix) and not f.startswith(exclude)]

    tables = sorted(pick("tables/"), key=lambda f: ("PARTITION OF" in files[f] or "INHERITS" in files[f], f))
    constraints = sorted(pick("constraints/"), key=lambda f: ("FOREIGN KEY" in files[f], f))
    order = (
        pick("grants/role.") + pick("types/") + tables + pick("functions/") + constraints + pick("indexes/")
        + pick("triggers/") + pick("policies/")
        + pick("grants/", ("grants/role.", "grants/default_privileges."))
        + pick("grants/default_privileges.")
    )
    assert set(order) == set(files)
    prelude = ("CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;\n"
               "CREATE SCHEMA app;\nCREATE SCHEMA \"App Data\";\n")
    return prelude + "\n".join(files[f] for f in order)


def test_round_trip_regenerates_identical_files(full: Project, tmp_path):
    clone = Project(tmp_path / "clone")
    clone.root.mkdir()
    clone.dbss("init")
    clone.migration("20261001000000_round_trip.sql", _round_trip_sql(full))
    clone.dbss("update")
    original, regenerated = full.snapshot(), clone.snapshot()
    assert set(regenerated) == set(original)
    for rel in original:
        assert regenerated[rel] == original[rel], rel


def test_policy_update_and_grant_revoke_follow_up(full: Project, tmp_path):
    p = Project(tmp_path / "followup")
    shutil.copytree(full.root, p.root)
    p.migration("20261001000500_followup.sql", """
        DROP POLICY "No archived edits" ON app.articles;
        ALTER TABLE app.articles NO FORCE ROW LEVEL SECURITY;
        REVOKE ALL ON app.articles FROM authenticated;
        REVOKE USAGE ON TYPE app.status FROM anon;
        DROP FUNCTION app.score(text);
        DROP INDEX app.articles_lower_title_idx;
        DROP TRIGGER authors_check ON app.authors;
        ALTER TYPE app.status ADD VALUE 'deleted';
        DROP ROLE app_reader;
    """.replace("DROP ROLE app_reader;", "REVOKE UPDATE (title) ON app.articles FROM app_reader;\n"
                "REVOKE USAGE ON SCHEMA app FROM app_reader;\nALTER DEFAULT PRIVILEGES IN SCHEMA app "
                "REVOKE SELECT ON TABLES FROM app_reader;\nDROP ROLE app_reader;"))
    p.dbss("update")
    files = p.files()
    policies = body(p, "policies/app.articles.sql")
    assert "No archived edits" not in policies and "FORCE" not in policies
    assert "grants/table.app.articles.sql" not in files
    assert "grants/type.app.status.sql" not in files
    assert "grants/role.app_reader.sql" not in files
    assert "grants/default_privileges.postgres.schema.app.sql" not in files
    assert "functions/app.score(text).sql" not in files and "functions/app.score(integer).sql" in files
    assert "indexes/app.articles.articles_lower_title_idx.sql" not in files
    assert "triggers/app.authors.authors_check.sql" not in files
    assert "'deleted'" in body(p, "types/app.status.sql")
    p.dbss("status", "--check")
